import type { EmployeeRecord } from "@/services/apis/employees/employee-service";

export type Employee = EmployeeRecord;
export type EmploymentStatus = Employee["status"];

export function formatDate(value: string) {
  return new Date(value).toLocaleDateString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
  });
}

export function initials(name: string) {
  return name
    .split(" ")
    .map((p) => p[0])
    .slice(0, 2)
    .join("")
    .toUpperCase();
}
